const dict = { en, th } as const;

/** The shipped dictionaries, for the admin copy editor. */
export const BASE_COPY = dict;

export type TKey = keyof typeof en;

type Vars = Record<string, string | number>;

export type CopyOverrides = { en: Record<string, string>; th: Record<string, string> };

function format(s: string, vars?: Vars) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => String(vars[k] ?? m));
}

/** Admin-edited wording, loaded once per session and layered over the dictionary. */
export async function fetchCopyOverrides(): Promise<CopyOverrides> {
  const empty: CopyOverrides = { en: {}, th: {} };
  try {
    const { supabase } = await import("@/integrations/supabase/client");
    const { data } = await supabase.from("copy_overrides").select("copy_key, lang, value");
    for (const row of data ?? []) {
      const lang = row.lang === "th" ? "th" : "en";
      if (row.copy_key && typeof row.value === "string") empty[lang][row.copy_key] = row.value;
    }
  } catch (error) {
    console.warn("[i18n] could not load copy overrides", error);
  }
  return empty;
}

const LangContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey, vars?: Vars) => string;
}>({ lang: "th", setLang: () => {}, t: (k) => th[k] });

export function LanguageProvider({ children }: { children: ReactNode }) {
  // Thai-first clinic: Thai is the default until the visitor picks English.
  const [lang, setLang] = useState<Lang>("th");

  const [overrides, setOverrides] = useState<CopyOverrides>({ en: {}, th: {} });

  useEffect(() => {
    const stored = window.localStorage.getItem("888clinic-lang");
    if (stored === "en" || stored === "th") setLang(stored);
  }, []);

  useEffect(() => {
    let alive = true;
    fetchCopyOverrides().then((o) => {
      if (alive) setOverrides(o);
    });
    return () => {
      alive = false;
    };
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang: (l: Lang) => {
        setLang(l);
        window.localStorage.setItem("888clinic-lang", l);
      },
      t: (k: TKey, vars?: Vars) =>
        format(overrides[lang][k] ?? dict[lang][k] ?? overrides.en[k] ?? en[k], vars),
    }),
    [lang, overrides],
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}

